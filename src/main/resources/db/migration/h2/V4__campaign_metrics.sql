create table campaign_metrics (
    campaign_id bigint not null,
    recorded_on date not null,
    reach_count bigint,
    impressions_count bigint,
    clicks_count bigint,
    conversions_count bigint,
    spend numeric(12,2),
    revenue numeric(12,2),
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    source varchar(120),
    notes varchar(2000),
    version bigint,
    primary key (id)
);

create index idx_campaign_metric_campaign on campaign_metrics (campaign_id, recorded_on);

alter table campaign_metrics
    add constraint fk_campaign_metric_campaign foreign key (campaign_id) references campaigns;
